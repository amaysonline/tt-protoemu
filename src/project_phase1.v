/*
 * Phase 1 top level: the v0 engine running a program baked into a ROM.
 * Configuration is fixed here; Phase 2 replaces all of this with the host interface.
 * Regenerate the ROM with:  python3 tools/asm.py programs/uart_tx_v0.s --vh src/rom.vh
 * SPDX-License-Identifier: Apache-2.0
 */
`default_nettype none

module tt_um_amaysonline_protoemu (
    input  wire [7:0] ui_in,
    output wire [7:0] uo_out,
    input  wire [7:0] uio_in,
    output wire [7:0] uio_out,
    output wire [7:0] uio_oe,
    input  wire       ena,
    input  wire       clk,
    input  wire       rst_n
);
    localparam [15:0] CLKDIV = 16'd3;      // tiny for fast simulation; 53 gives 115200 baud

    // ROM: generated by the assembler
    reg [15:0] rom_data;
    wire [4:0] pc;
    always @(*) begin
        case (pc)
`include "rom.vh"
            default: rom_data = 16'h0000;   // jmp 0
        endcase
    end

    // clock divider
    reg [15:0] divcnt;
    wire tick = (divcnt >= CLKDIV);
    always @(posedge clk) begin
        if (!rst_n || tick) divcnt <= 16'd0;
        else                divcnt <= divcnt + 16'd1;
    end

    // input synchroniser (not needed by v0 programs, but the core expects one)
    reg [7:0] pin_s1, pin_s2;
    always @(posedge clk) begin
        pin_s1 <= uio_in;
        pin_s2 <= pin_s1;
    end

    wire [7:0] out_val;
    pe_core u_core (
        .clk(clk), .rst_n(rst_n), .en(1'b1), .restart(1'b0), .tick(tick),
        .pc_o(pc), .instr(rom_data),
        .pins_in(pin_s2), .out_val(out_val),
        .out_base(3'd0), .in_base(3'd0), .set_base(3'd0), .set_count(3'd1),
        .side_pin(3'd0), .jmp_pin(3'd0), .out_msb(1'b0), .in_msb(1'b0), .watch_mask(8'hFF),
        .tx_empty(1'b1), .tx_data(8'd0), .tx_pop(),
        .rx_full(1'b0), .rx_data(), .rx_push(), .rx_drop(),
        .irq(), .irq_clr(1'b0), .stalled(), .x_o(), .y_o()
    );

    // pin 0 is a push-pull output in Phase 1; the other pins stay inputs
    assign uio_out = {7'b0, out_val[0]};
    assign uio_oe  = 8'b0000_0001;
    assign uo_out  = 8'b0;

    wire _unused = &{ena, ui_in, 1'b0};
endmodule
